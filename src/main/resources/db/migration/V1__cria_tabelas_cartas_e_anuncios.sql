CREATE TABLE cartas (
    id             VARCHAR(64)  PRIMARY KEY,
    nome           VARCHAR(255) NOT NULL,
    imagem_pequena VARCHAR(512),
    imagem_grande  VARCHAR(512),
    colecao        VARCHAR(255),
    raridade       VARCHAR(255),
    numero         VARCHAR(64)
);

CREATE TABLE anuncios (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carta_id  VARCHAR(64)      NOT NULL REFERENCES cartas (id),
    preco     DOUBLE PRECISION NOT NULL,
    condicao  VARCHAR(50),
    descricao VARCHAR(300),
    vendedor  VARCHAR(40),
    status    VARCHAR(20)      NOT NULL
);

CREATE INDEX idx_anuncios_carta_id ON anuncios (carta_id);
